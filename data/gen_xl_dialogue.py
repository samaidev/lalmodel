def build_samples():
    samples = []

    # 各主题数据, 每条重复若干次 (增加曝光率)
    groups = [WHY, WHAT, HOW, FACT, CHAT, MATH, SCIENCE, BODY, SOCIAL, DAILY]
    reps =   [4,   4,    4,   3,    5,    3,    3,      3,    3,      3]

    for group, rep in zip(groups, reps):
        for q, a in group:
            text = f"问：{q}\n答：{a}"
            for _ in range(rep):
                samples.append(text)

    # 同义改写变体
    for orig_q, var_q, ans in VARIANTS_Q:
        text = f"问：{var_q}\n答：{ans}"
        for _ in range(4):
            samples.append(text)

    # 随机打乱
    random.shuffle(samples)
    return samples


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/xl_dialogue.jsonl")
    args = ap.parse_args()

    samples = build_samples()

    with open(args.out, "w", encoding="utf-8") as f:
        for i, text in enumerate(samples):
            obj = {
                "id": f"xdlg-{i:05d}",
                "stage": 1,
                "subject": "dialogue",
                "type": "synthetic",
                "text": text,
            }
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")

    print(f"[*] wrote {len(samples)} XL dialogue samples -> {args.out}")

    # 统计
    categories = {"WHY": len(WHY), "WHAT": len(WHAT), "HOW": len(HOW),
                  "FACT": len(FACT), "CHAT": len(CHAT), "MATH": len(MATH),
                  "SCIENCE": len(SCIENCE), "BODY": len(BODY), "SOCIAL": len(SOCIAL),
                  "DAILY": len(DAILY), "VARIANTS": len(VARIANTS_Q)}
    print(f"[*] Categories:")
    for cat, count in categories.items():
        print(f"    {cat}: {count} unique")
    print(f"    Total unique: {sum(categories.values())}")


if __name__ == "__main__":
    main()
