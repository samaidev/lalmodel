CONN_START = ["因为", "由于"]
CONN_MID = ["接着", "然后", "同时", "这样一来"]
CONN_END = ["所以", "因此", "于是"]


def _starts_conn(clause):
    for c in ("所以", "因此", "于是", "因为", "由于"):
        if clause.startswith(c):
            return True
    return False


def _join_chain(clauses, conn_start, conn_end):
    """组装因果链: 首句加原因连词, 尾句加结论连词(避免与句内自带连词冲突)"""
    parts = [f"{conn_start}{clauses[0]}"]
    parts += list(clauses[1:-1])
    last = clauses[-1]
    if not _starts_conn(last):
        last = f"{conn_end}{last}"
    parts.append(last)
    return "。".join(parts) + "。"


def _drop_one_mid(clauses, rng):
    """随机去掉一个中间句 (保留顺序与因果), 30% 概率"""
    if len(clauses) >= 4 and rng.random() < 0.3:
        i = rng.randrange(1, len(clauses) - 1)
        return clauses[:i] + clauses[i+1:]
    return clauses


def build_samples():
    out = []
    rng = random.Random(20260808)

    # 1. 精选
    for i, (q, a) in enumerate(CURATED):
        out.append({"q": f"问：{q} 答：{a}", "t": "curated"})

    # 2. 因果: 连词变体 × 中间句删减
    for topic, phenomenon, chain in CAUSAL:
        for cs, ce in zip(CONN_START, CONN_END):
            body = _join_chain(chain, cs, ce)
            out.append({"q": f"问：{topic}？ 答：{body}", "t": "causal"})
            body2 = _join_chain(_drop_one_mid(chain, rng), cs, ce)
            if body2 != body:
                out.append({"q": f"问：{topic}？ 答：{body2}", "t": "causal"})
        # 现象开头变体
        body3 = "。".join([phenomenon] + chain[:-1] + [chain[-1] if _starts_conn(chain[-1]) else CONN_END[2] + chain[-1]]) + "。"
        out.append({"q": f"问：{topic}？ 答：{body3}", "t": "causal"})

    # 3. 定义: 句序变体
    for subj, cat, props, funcs in DEFINE:
        body_a = f"{cat}。" + "。".join(props) + "。" + "。".join(funcs) + "。"
        out.append({"q": f"问：{subj}？ 答：{body_a}", "t": "define"})
        body_b = f"{cat}。" + "。".join(props[:2] + funcs[:1] + props[2:]) + "。"
        out.append({"q": f"问：{subj}？ 答：{body_b}", "t": "define"})
        body_c = f"{cat}。" + "。".join(funcs + props) + "。"
        if subj.startswith("什么是"):
            out.append({"q": f"请介绍一下{subj[2:]}。 答：{body_c}", "t": "define"})
        else:
            out.append({"q": f"问：{subj}？ 答：{body_c}", "t": "define"})

    # 4. 过程: 步骤子集 + 开场变体
    for q, steps in PROCESS:
        body_a = "。".join(steps) + "。"
        out.append({"q": f"问：{q}？ 答：{body_a}", "t": "process"})
        out.append({"q": f"问：{q}？ 答：方法很简单。" + "。".join(steps) + "。", "t": "process"})
        if len(steps) >= 4:
            body_c = "。".join(steps[:1] + steps[2:]) + "。"
            out.append({"q": f"问：{q}？ 答：{body_c}", "t": "process"})

    # 5. 陈述回应 + 认同词变体
    for stmt, reply in STATEMENTS:
        out.append({"q": f"{stmt}\n{reply}", "t": "statement"})
        reply2 = reply.replace("对，", "没错，").replace("是的，", "对，")
        if reply2 != reply:
            out.append({"q": f"{stmt}\n{reply2}", "t": "statement"})

    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/long_dialogue.jsonl")
    args = ap.parse_args()

    samples = build_samples()
    random.shuffle(samples)

    with open(args.out, "w", encoding="utf-8") as f:
        for i, s in enumerate(samples):
            rec = {
                "id": f"long-{i:05d}",
                "stage": 1,
                "subject": "dialogue",
                "type": s["t"],
                "text": s["q"],
            }
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    lens = [len(s["q"]) for s in samples]
    lens.sort()
    print(f"[*] wrote {len(samples)} long dialogue samples -> {args.out}")
    print(f"[*] char len: min={lens[0]} median={lens[len(lens)//2]} max={lens[-1]}")
    from collections import Counter
    print("[*] types:", dict(Counter(s["t"] for s in samples)))


if __name__ == "__main__":
    main()
