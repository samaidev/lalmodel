CHAT = [
    ("在吗？", "在的，有什么我可以帮你的吗？"),
    ("今天天气真好。", "是啊，阳光明媚，正适合出门走走。"),
    ("我有点累。", "那你要好好休息，喝口水放松一下。"),
    ("谢谢你。", "不客气，能帮到你就好。"),
    ("再见。", "再见，祝你一天都顺顺利利的。"),
    ("你喜欢什么？", "我喜欢学习新知识，也喜欢和你聊天。"),
    ("讲个故事吧。", "从前有只小鸟，它天天练习飞翔，终于飞上了高高的蓝天。"),
    ("你几岁了？", "我没有年龄，不过我一直在学习和成长。"),
]


def build_samples():
    samples = []
    # 核心样例: 高权重重复多次, 确保模型必会
    for q, a in CORE:
        for _ in range(6):
            samples.append(f"{q}\n{a}")
    # 各主题: 每对重复若干次
    groups = [WHY, WHAT, HOW, FACT, CHAT]
    reps = [3, 3, 3, 3, 4]
    for g, r in zip(groups, reps):
        for q, a in g:
            for _ in range(r):
                samples.append(f"{q}\n{a}")
    # 额外微扰: 同义改写, 增强鲁棒性
    variants = {
        "鸟为什么天上飞？": "小鸟凭什么能飞上天？",
        "什么是火？": "火到底是什么？",
        "天为什么是蓝色的？": "天空为何看上去蓝蓝的？",
        "你好": "您好",
        "水为什么会结冰？": "天冷了水怎么就冻住了？",
    }
    ans_map = {
        "小鸟凭什么能飞上天？": "因为小鸟有翅膀，扇动翅膀产生升力就能飞上天。",
        "火到底是什么？": "火是燃烧时放出的光和热，是一种剧烈氧化现象。",
        "天空为何看上去蓝蓝的？": "因为阳光中蓝光最易被空气散射，天空便显出蓝色。",
        "您好": "您好！很高兴为您服务。",
        "天冷了水怎么就冻住了？": "因为温度降到零度以下，水分子结成冰晶，水就冻住了。",
    }
    for q, qv in variants.items():
        a = ans_map[qv]
        for _ in range(3):
            samples.append(f"{qv}\n{a}")
    random.shuffle(samples)
    return samples


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/dialogue_train.jsonl")
    args = ap.parse_args()
    samples = build_samples()
    n_written = 0
    with open(args.out, "w", encoding="utf-8") as f:
        for i, text in enumerate(samples):
            obj = {
                "id": f"dlg-{i:05d}",
                "stage": 1,
                "subject": "dialogue",
                "type": "synthetic",
                "text": text,
            }
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")
            n_written += 1
    print(f"[*] wrote {n_written} dialogue samples -> {args.out}")


if __name__ == "__main__":
    main()
